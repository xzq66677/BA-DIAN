/**
 * 构建：把真实规则引擎 + AI + 模拟器 bundle 为零依赖单文件 JS。
 * Worker 代码作为字符串内联，用 eval Worker 启动，满足「单文件」交付要求。
 * 源码层只 import，绝不复制规则。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

// 允许在独立 worktree（无 node_modules）构建：从环境变量指定的仓库解析 esbuild
const toolRoot = process.env.SIM_TOOL_ROOT || 'D:/AI工作区/badian-game';
const require = createRequire(path.join(toolRoot, 'package.json'));
const { build } = require('esbuild');

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const outDir = path.resolve(root, 'dist-sim');
fs.mkdirSync(outDir, { recursive: true });

// 构建时冻结代码版本（干净包无 .git，运行时无法读取）
const { execFileSync } = await import('node:child_process');
let codeCommit = 'unknown', codeDirty = false;
try {
  codeCommit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  codeDirty = execFileSync('git', ['status', '--porcelain'], { cwd: root, encoding: 'utf8' }).trim().length > 0;
} catch { /* 非 git 环境 */ }
const versionFile = path.join(here, 'src/_build-version.ts');
fs.writeFileSync(versionFile, `/* AUTO-GENERATED by build.mjs */\nexport const BUILD_VERSION = { commit: ${JSON.stringify(codeCommit)}, dirty: ${codeDirty} };\n`);
console.log(`[build] version ${codeCommit.slice(0, 8)} dirty=${codeDirty}`);

// 1) bundle worker → 字符串
const workerBundle = await build({
  entryPoints: [path.join(here, 'src/worker.ts')],
  bundle: true,
  platform: 'node',
  format: 'cjs', // eval Worker 默认按 CJS 解析，必须用 cjs
  target: 'node20',
  write: false,
  logLevel: 'warning',
});
const workerCode = workerBundle.outputFiles[0].text;
const embedded = path.join(here, 'src/_worker-embedded.ts');
fs.writeFileSync(embedded, `/* AUTO-GENERATED by build.mjs — worker bundle inlined */\nexport const WORKER_CODE = ${JSON.stringify(workerCode)};\n`);

// 2) bundle 主入口（引用内联 worker）
const mainBundle = await build({
  entryPoints: [path.join(here, 'src/main.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  write: false,
  logLevel: 'warning',
});
fs.writeFileSync(path.join(outDir, 'sim.js'), mainBundle.outputFiles[0].text);

// 3) bundle verify / replay / merge 三个工具
for (const name of ['verify', 'replay', 'merge']) {
  const r = await build({
    entryPoints: [path.join(here, `src/${name}.ts`)],
    bundle: true, platform: 'node', format: 'esm', target: 'node20', write: false, logLevel: 'warning',
  });
  fs.writeFileSync(path.join(outDir, `${name}.js`), r.outputFiles[0].text);
}

// 恢复占位，保证源码层 tsc 始终可编译
fs.writeFileSync(embedded, `/* 占位：build.mjs 会覆盖本文件，把 worker bundle 内联为字符串。 */\nexport const WORKER_CODE = '';\n`);
fs.writeFileSync(versionFile, `/* 占位：build.mjs 会覆盖本文件，冻结构建时的 git commit + dirty 标志。 */\nexport const BUILD_VERSION = { commit: 'unknown', dirty: false };\n`);
console.log(`[build] dist-sim/ 单文件产物：${fs.readdirSync(outDir).join(', ')}`);
console.log(`[build] sim.js ${(fs.statSync(path.join(outDir, 'sim.js')).size / 1024).toFixed(0)} KB · worker 内联 ${(workerCode.length / 1024).toFixed(0)} KB`);
